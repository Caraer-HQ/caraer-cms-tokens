/**
 * Regenerates `src/tokens.css` from `src/defaults.ts`.
 *
 * The stylesheet exists so a module developer running Astro locally, with no
 * company attached, still renders against real token values. Keeping it
 * generated means it cannot drift from the defaults the server resolves.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

import { DEFAULT_DARK_COLORS, DEFAULT_TOKENS } from '../src/defaults.ts';
import { toCustomProperties } from '../src/schema.ts';

const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, '..', 'src', 'tokens.css');

const light = toCustomProperties(DEFAULT_TOKENS);
const dark = toCustomProperties({ ...DEFAULT_TOKENS, colorScheme: 'dark', color: DEFAULT_DARK_COLORS });

const declarations = (tokens) =>
  Object.entries(tokens)
    .map(([name, value]) => `  ${name}: ${value};`)
    .join('\n');

// Only colour tokens differ between schemes, so the dark block stays minimal.
const darkOverrides = Object.fromEntries(
  Object.entries(dark).filter(([name, value]) => light[name] !== value),
);

const css = `/*
 * GENERATED by scripts/generate-css.mjs - do not edit by hand.
 *
 * Default values for every Caraer CMS design token. In production the server
 * writes the company's resolved tokens onto <html> as inline custom properties,
 * which override these. Import this file in local module development so your
 * component renders against real values without a company attached.
 */
:root {
${declarations(light)}
}

[data-caraer-scheme='dark'] {
${declarations(darkOverrides)}
}
`;

writeFileSync(target, css, 'utf8');
console.log(`Wrote ${Object.keys(light).length} tokens to ${target}`);
